-- Haramain Collection backoffice extension
-- Run once in Supabase SQL Editor after schema.sql.

create table if not exists public.store_settings (
  id smallint primary key default 1 check (id = 1),
  store_name text not null default 'Haramain Collection',
  announcement_text text not null default 'FREE GIFT PACKING ON ORDERS ABOVE ₹1,499 · ORDER ON WHATSAPP',
  announcement_enabled boolean not null default true,
  hero_eyebrow text not null default 'Faith · Fragrance · Gifting',
  hero_title text not null default 'Thoughtful treasures for sacred moments.',
  hero_copy text not null default 'Discover Islamic gifts, beautiful home fragrances and trusted Hajj and Umrah essentials—chosen with care for your family and every meaningful occasion.',
  hero_note text not null default 'Easy WhatsApp ordering · Secure packing · Delivery across India',
  hero_primary_label text not null default 'Explore collection',
  hero_primary_link text not null default 'shop.html',
  hero_image_url text not null default 'WhatsApp Image 2026-09-27 at 3.27.53 PM.jpeg',
  primary_color text not null default '#718c72',
  primary_dark_color text not null default '#34473a',
  accent_color text not null default '#9a8265',
  background_color text not null default '#faf8f2',
  whatsapp_number text not null default '919303081471',
  upi_id text not null default 'yourname@upi',
  footer_copy text not null default 'Islamic essentials, fragrances and meaningful gifts—carefully chosen for homes and sacred journeys.',
  shipping_note text not null default 'Shipping and final stock availability will be confirmed on WhatsApp.',
  updated_at timestamptz not null default now()
);

-- These make the script safe to re-run if the original table already exists.
alter table public.store_settings add column if not exists hero_image_url text not null default 'WhatsApp Image 2026-09-27 at 3.27.53 PM.jpeg';
alter table public.store_settings add column if not exists primary_color text not null default '#718c72';
alter table public.store_settings add column if not exists primary_dark_color text not null default '#34473a';
alter table public.store_settings add column if not exists accent_color text not null default '#9a8265';
alter table public.store_settings add column if not exists background_color text not null default '#faf8f2';

create table if not exists public.coupons (
  id bigint generated by default as identity primary key,
  code text not null unique,
  label text not null,
  discount_percent numeric(5, 2) not null check (discount_percent > 0 and discount_percent <= 100),
  min_cart_value numeric(10, 2) not null default 0 check (min_cart_value >= 0),
  min_items integer not null default 0 check (min_items >= 0),
  auto_apply boolean not null default true,
  active boolean not null default false,
  priority integer not null default 0,
  starts_at timestamptz,
  ends_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

drop trigger if exists store_settings_set_updated_at on public.store_settings;
create trigger store_settings_set_updated_at before update on public.store_settings
for each row execute function public.set_updated_at();

drop trigger if exists coupons_set_updated_at on public.coupons;
create trigger coupons_set_updated_at before update on public.coupons
for each row execute function public.set_updated_at();

alter table public.store_settings enable row level security;
alter table public.coupons enable row level security;

drop policy if exists "Public can view store settings" on public.store_settings;
create policy "Public can view store settings" on public.store_settings
for select using (true);

drop policy if exists "Admins can update store settings" on public.store_settings;
create policy "Admins can update store settings" on public.store_settings
for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Public can view active coupons" on public.coupons;
create policy "Public can view active coupons" on public.coupons
for select using (active = true or public.is_admin());

drop policy if exists "Admins can manage coupons" on public.coupons;
create policy "Admins can manage coupons" on public.coupons
for all to authenticated using (public.is_admin()) with check (public.is_admin());

